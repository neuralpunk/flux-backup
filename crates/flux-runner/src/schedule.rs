//! Automatic backups through systemd timers.
//!
//! For each scheduled profile Flux writes, into `~/.config/systemd/user/` (or
//! `/etc/systemd/system/` for system profiles):
//!
//! * `flux-backup-<id>.service`: runs `flux backup <id> --scheduled`
//! * `flux-backup-<id>.timer`:
//!   - calendar schedules: `OnCalendar=<expr>`, with `Persistent=` catching up on runs missed
//!     while the machine was off
//!   - interval schedules: a frequent check (`OnStartupSec` + `OnUnitActiveSec`) that runs
//!     the service with `--if-due`; Flux compares the last successful run with the interval
//!     itself (anacron-style), so a backup missed during downtime runs soon after login
//! * `flux-backup-<id>.connect.service`, for `on_connect`: wanted by the drive's mount unit,
//!   so it starts when the drive is mounted
//!
//! Generated files start with [`MARKER`]. Flux only ever modifies or removes files that
//! carry it.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use serde::Serialize;

use flux_core::profile::{Profile, Target, Trigger};
use flux_core::{Paths, ProfileId, Scope, sys};

pub const MARKER: &str = "# Generated by Flux Backup";
const PREFIX: &str = "flux-backup-";

#[derive(Debug, thiserror::Error)]
pub enum ScheduleError {
    #[error("{0}: {1}")]
    Io(PathBuf, #[source] std::io::Error),
    #[error("`systemctl {args}` failed: {stderr}")]
    Systemctl { args: String, stderr: String },
    #[error("invalid calendar expression {expr:?}: {message}")]
    BadCalendar { expr: String, message: String },
    #[error("backup on connect needs target.fs_uuid and a local target")]
    NoDrive,
    #[error(
        "cannot tell where the drive {0} gets mounted; connect it once and run `flux schedule install` again"
    )]
    UnknownMountPoint(String),
    #[error("{0} exists but was not generated by Flux; refusing to overwrite it")]
    Foreign(PathBuf),
}

/// How Flux talks to systemd. Overridable for tests: `FLUX_SYSTEMD_UNIT_DIR` and
/// `FLUX_SYSTEMCTL` (a program called instead of `systemctl`).
#[derive(Debug, Clone)]
pub struct Systemd {
    pub scope: Scope,
    pub unit_dir: PathBuf,
    systemctl: String,
}

impl Systemd {
    pub fn new(paths: &Paths) -> Self {
        let unit_dir = std::env::var_os("FLUX_SYSTEMD_UNIT_DIR")
            .map(PathBuf::from)
            .unwrap_or_else(|| match paths.scope {
                Scope::System => PathBuf::from("/etc/systemd/system"),
                Scope::User => std::env::var_os("XDG_CONFIG_HOME")
                    .map(PathBuf::from)
                    .filter(|p| p.is_absolute())
                    .or_else(|| sys::home_dir().map(|h| h.join(".config")))
                    .unwrap_or_else(|| PathBuf::from(".config"))
                    .join("systemd/user"),
            });
        let systemctl = std::env::var("FLUX_SYSTEMCTL").unwrap_or_else(|_| "systemctl".into());
        Self {
            scope: paths.scope,
            unit_dir,
            systemctl,
        }
    }

    pub fn run(&self, args: &[&str]) -> Result<String, ScheduleError> {
        let mut cmd = Command::new(&self.systemctl);
        if self.scope == Scope::User {
            cmd.arg("--user");
        }
        let out = cmd
            .args(args)
            .output()
            .map_err(|e| ScheduleError::Systemctl {
                args: args.join(" "),
                stderr: e.to_string(),
            })?;
        if !out.status.success() {
            return Err(ScheduleError::Systemctl {
                args: args.join(" "),
                stderr: String::from_utf8_lossy(&out.stderr).trim().to_owned(),
            });
        }
        Ok(String::from_utf8_lossy(&out.stdout).trim().to_owned())
    }

    fn property(&self, unit: &str, prop: &str) -> Option<String> {
        self.run(&["show", unit, "-p", prop, "--value"])
            .ok()
            .filter(|v| !v.is_empty() && v != "n/a")
    }
}

pub fn service_name(id: &ProfileId) -> String {
    format!("{PREFIX}{id}.service")
}
pub fn timer_name(id: &ProfileId) -> String {
    format!("{PREFIX}{id}.timer")
}
pub fn connect_name(id: &ProfileId) -> String {
    // Profile ids can't contain '.', so this can't collide with another profile's units.
    format!("{PREFIX}{id}.connect.service")
}

/// `systemd-escape --path`: unit name of a path, e.g. `/run/media/me/My Disk` →
/// `run-media-me-My\x20Disk`.
pub fn escape_path(path: &Path) -> String {
    let s = path.as_os_str().as_encoded_bytes();
    let trimmed: &[u8] = {
        let mut t = s;
        while let [b'/', rest @ ..] = t {
            t = rest;
        }
        while let [rest @ .., b'/'] = t {
            t = rest;
        }
        t
    };
    if trimmed.is_empty() {
        return "-".into();
    }
    let mut out = String::new();
    let mut prev_slash = false;
    for (i, &b) in trimmed.iter().enumerate() {
        if b == b'/' {
            if !prev_slash {
                out.push('-');
            }
            prev_slash = true;
            continue;
        }
        prev_slash = false;
        let plain = b.is_ascii_alphanumeric() || b == b':' || b == b'_' || (b == b'.' && i > 0);
        if plain {
            out.push(b as char);
        } else {
            let _ = write!(out, "\\x{b:02x}");
        }
    }
    out
}

/// Interval between "is it due?" checks for interval schedules.
fn check_period(every: Duration) -> Duration {
    every
        .min(Duration::from_secs(15 * 60))
        .max(Duration::from_secs(60))
}

fn systemd_span(d: Duration) -> String {
    format!("{}s", d.as_secs())
}

fn quote(arg: &str) -> String {
    // systemd ExecStart= quoting: double quotes, escape backslash and quote.
    if arg
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || "/-_.:=@".contains(c))
    {
        arg.to_owned()
    } else {
        format!("\"{}\"", arg.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

/// Inputs for unit generation that come from the environment, not the profile.
#[derive(Debug, Clone)]
pub struct UnitEnv {
    /// Absolute path of the `flux` binary to run.
    pub flux_bin: PathBuf,
    pub scope: Scope,
    /// Propagated `FLUX_HOME`, if set.
    pub flux_home: Option<PathBuf>,
}

impl UnitEnv {
    pub fn current(scope: Scope) -> Self {
        let flux_bin = std::env::current_exe().unwrap_or_else(|_| PathBuf::from("/usr/bin/flux"));
        // An installed binary is preferred over a path inside a build tree; keep what runs.
        Self {
            flux_bin,
            scope,
            flux_home: std::env::var_os("FLUX_HOME").map(PathBuf::from),
        }
    }
}

/// The units a profile needs: (file name, contents).
pub fn units_for(
    id: &ProfileId,
    p: &Profile,
    env: &UnitEnv,
) -> Result<Vec<(String, String)>, ScheduleError> {
    let mut units = Vec::new();
    let s = &p.schedule;
    let if_due = s.trigger == Trigger::Interval;
    let header = format!(
        "{MARKER} for profile \"{id}\". It is overwritten by `flux schedule`; change the profile instead.\n"
    );
    let exec = {
        let mut a = vec![env.flux_bin.display().to_string()];
        if env.scope == Scope::System {
            a.push("--system".into());
        }
        a.extend(["backup".into(), id.to_string(), "--scheduled".into()]);
        if if_due {
            a.push("--if-due".into());
        }
        a.iter().map(|x| quote(x)).collect::<Vec<_>>().join(" ")
    };
    let service_body = |description: String| {
        let mut u = header.clone();
        let _ = writeln!(
            u,
            "[Unit]\nDescription={description}\nDocumentation=https://github.com/neuralpunk/flux-backup"
        );
        if let Some(h) = &env.flux_home {
            let _ = writeln!(
                u,
                "\n[Service]\nEnvironment={}",
                quote(&format!("FLUX_HOME={}", h.display()))
            );
        } else {
            u.push_str("\n[Service]\n");
        }
        let _ = writeln!(
            u,
            "Type=oneshot\nExecStart={exec}\n# Let Flux stop cleanly; the partial snapshot is resumed next time.\nKillSignal=SIGINT\nTimeoutStopSec=300"
        );
        u
    };

    if s.trigger != Trigger::Manual {
        units.push((
            service_name(id),
            service_body(format!("Flux Backup: {}", p.name)),
        ));
        let mut t = header.clone();
        let _ = writeln!(
            t,
            "[Unit]\nDescription=Flux Backup schedule: {}\n\n[Timer]",
            p.name
        );
        match s.trigger {
            Trigger::Calendar => {
                let expr = s.on_calendar.as_deref().unwrap_or("daily");
                let _ = writeln!(
                    t,
                    "OnCalendar={expr}\nPersistent={}",
                    if s.catch_up { "true" } else { "false" }
                );
            }
            Trigger::Interval => {
                let every = s
                    .every
                    .map_or(Duration::from_secs(86_400), |e| e.as_duration());
                let _ = writeln!(
                    t,
                    "# Checks every {} whether the backup is due (every {}).\nOnStartupSec=120s\nOnUnitActiveSec={}",
                    humantime_short(check_period(every)),
                    humantime_short(every),
                    systemd_span(check_period(every))
                );
            }
            Trigger::Manual => unreachable!(),
        }
        let _ = writeln!(
            t,
            "AccuracySec=60s\nUnit={}\n\n[Install]\nWantedBy=timers.target",
            service_name(id)
        );
        units.push((timer_name(id), t));
    }

    if s.on_connect {
        let Target::Local {
            path,
            fs_uuid: Some(uuid),
        } = &p.target
        else {
            return Err(ScheduleError::NoDrive);
        };
        let mount = sys::mount_point_for_uuid(uuid)
            .or_else(|| sys::guess_mount_point(path))
            .ok_or_else(|| ScheduleError::UnknownMountPoint(uuid.clone()))?;
        let mount_unit = format!("{}.mount", escape_path(&mount));
        let mut c = service_body(format!(
            "Flux Backup when {} is connected: {}",
            mount.display(),
            p.name
        ));
        c = c.replacen(
            "Documentation=https://github.com/neuralpunk/flux-backup\n",
            &format!("Documentation=https://github.com/neuralpunk/flux-backup\nAfter={mount_unit}\nRequisite={mount_unit}\n"),
            1,
        );
        let _ = writeln!(c, "\n[Install]\nWantedBy={mount_unit}");
        units.push((connect_name(id), c));
    }
    Ok(units)
}

fn humantime_short(d: Duration) -> String {
    humantime_fmt(d.as_secs())
}

fn humantime_fmt(secs: u64) -> String {
    match secs {
        s if s % 86_400 == 0 => format!("{}d", s / 86_400),
        s if s % 3600 == 0 => format!("{}h", s / 3600),
        s if s % 60 == 0 => format!("{}min", s / 60),
        s => format!("{s}s"),
    }
}

/// Check a calendar expression with `systemd-analyze calendar`. Returns the next elapse
/// time as systemd prints it. If systemd-analyze is missing, accepts the expression.
pub fn check_calendar(expr: &str) -> Result<Option<String>, ScheduleError> {
    let Ok(out) = Command::new("systemd-analyze")
        .args(["calendar", expr])
        .output()
    else {
        return Ok(None);
    };
    if !out.status.success() {
        let message = String::from_utf8_lossy(&out.stderr).trim().to_owned();
        return Err(ScheduleError::BadCalendar {
            expr: expr.into(),
            message,
        });
    }
    Ok(String::from_utf8_lossy(&out.stdout).lines().find_map(|l| {
        l.trim()
            .strip_prefix("Next elapse:")
            .map(|v| v.trim().to_owned())
    }))
}

fn is_ours(path: &Path) -> bool {
    fs::read_to_string(path).is_ok_and(|t| t.starts_with(MARKER))
}

/// What `install`/`sync` did for one profile.
#[derive(Debug, Default, Serialize)]
pub struct Applied {
    pub written: Vec<String>,
    pub removed: Vec<String>,
    pub unchanged: Vec<String>,
}

impl Applied {
    pub fn changed(&self) -> bool {
        !self.written.is_empty() || !self.removed.is_empty()
    }
}

/// Make the installed units match the profile: write/enable what it needs, remove what it
/// no longer needs.
pub fn apply(
    sd: &Systemd,
    id: &ProfileId,
    p: &Profile,
    env: &UnitEnv,
) -> Result<Applied, ScheduleError> {
    if p.schedule.trigger == Trigger::Calendar
        && let Some(expr) = &p.schedule.on_calendar
    {
        check_calendar(expr)?;
    }
    let wanted = units_for(id, p, env)?;
    let mut applied = Applied::default();
    fs::create_dir_all(&sd.unit_dir).map_err(|e| ScheduleError::Io(sd.unit_dir.clone(), e))?;

    for (name, body) in &wanted {
        let path = sd.unit_dir.join(name);
        match fs::read_to_string(&path) {
            Ok(cur) if cur == *body => applied.unchanged.push(name.clone()),
            Ok(_) if !is_ours(&path) => return Err(ScheduleError::Foreign(path)),
            _ => {
                flux_core::store::write_atomic(&path, body.as_bytes(), 0o644)
                    .map_err(|e| ScheduleError::Io(path.clone(), std::io::Error::other(e)))?;
                applied.written.push(name.clone());
            }
        }
    }
    let all = [service_name(id), timer_name(id), connect_name(id)];
    let stale: Vec<&String> = all
        .iter()
        .filter(|n| !wanted.iter().any(|(w, _)| w == *n))
        .collect();
    for name in &stale {
        let path = sd.unit_dir.join(name);
        if path.exists() && is_ours(&path) {
            if name.ends_with(".timer") || name.ends_with(".connect.service") {
                let _ = sd.run(&["disable", "--now", name]);
            }
            fs::remove_file(&path).map_err(|e| ScheduleError::Io(path.clone(), e))?;
            applied.removed.push((*name).clone());
        }
    }

    if applied.changed() {
        sd.run(&["daemon-reload"])?;
    }
    for (name, _) in &wanted {
        if name.ends_with(".timer") {
            sd.run(&["enable", "--now", name])?;
            if applied.written.contains(name) {
                // Pick up a changed OnCalendar without waiting for the old schedule.
                let _ = sd.run(&["restart", name]);
            }
        } else if name.ends_with(".connect.service") {
            sd.run(&["enable", name])?;
        }
    }
    Ok(applied)
}

/// Remove all of a profile's units.
pub fn remove(sd: &Systemd, id: &ProfileId) -> Result<Applied, ScheduleError> {
    let mut applied = Applied::default();
    for name in [timer_name(id), connect_name(id), service_name(id)] {
        let path = sd.unit_dir.join(&name);
        if path.exists() && is_ours(&path) {
            if name != service_name(id) {
                let _ = sd.run(&["disable", "--now", &name]);
            }
            fs::remove_file(&path).map_err(|e| ScheduleError::Io(path.clone(), e))?;
            applied.removed.push(name);
        }
    }
    if applied.changed() {
        sd.run(&["daemon-reload"])?;
    }
    Ok(applied)
}

/// Profile ids that have Flux-generated units installed.
pub fn installed_ids(sd: &Systemd) -> Vec<ProfileId> {
    let Ok(rd) = fs::read_dir(&sd.unit_dir) else {
        return Vec::new();
    };
    let mut ids: Vec<ProfileId> = rd
        .flatten()
        .filter(|e| is_ours(&e.path()))
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let stem = name.strip_prefix(PREFIX)?;
            let stem = stem
                .strip_suffix(".timer")
                .or_else(|| stem.strip_suffix(".connect.service"))
                .or_else(|| stem.strip_suffix(".service"))?;
            ProfileId::new(stem).ok()
        })
        .collect();
    ids.sort();
    ids.dedup();
    ids
}

#[derive(Debug, Serialize)]
pub struct ScheduleStatus {
    pub profile: String,
    /// Human summary of the profile's schedule.
    pub schedule: String,
    pub installed: bool,
    /// Installed units differ from what the profile asks for.
    pub out_of_date: bool,
    pub timer_active: bool,
    pub next_run: Option<String>,
    pub last_trigger: Option<String>,
}

pub fn summary(p: &Profile) -> String {
    let s = &p.schedule;
    let mut out = match s.trigger {
        Trigger::Manual => "manual".to_owned(),
        Trigger::Calendar => s.on_calendar.clone().unwrap_or_default(),
        Trigger::Interval => s.every.map(|e| format!("every {e}")).unwrap_or_default(),
    };
    if s.on_connect {
        out.push_str(" + when drive connected");
    }
    out
}

pub fn status(sd: &Systemd, id: &ProfileId, p: &Profile, env: &UnitEnv) -> ScheduleStatus {
    let wanted = units_for(id, p, env).unwrap_or_default();
    let installed_any = [service_name(id), timer_name(id), connect_name(id)]
        .iter()
        .any(|n| sd.unit_dir.join(n).exists());
    let out_of_date = wanted.iter().any(|(n, body)| {
        fs::read_to_string(sd.unit_dir.join(n)).ok().as_deref() != Some(body.as_str())
    }) || (wanted.is_empty() && installed_any);
    let timer = timer_name(id);
    let has_timer = sd.unit_dir.join(&timer).exists();
    ScheduleStatus {
        profile: id.to_string(),
        schedule: summary(p),
        installed: installed_any,
        out_of_date,
        timer_active: has_timer && sd.property(&timer, "ActiveState").as_deref() == Some("active"),
        next_run: if has_timer {
            sd.property(&timer, "NextElapseUSecRealtime")
        } else {
            None
        },
        last_trigger: if has_timer {
            sd.property(&timer, "LastTriggerUSec")
        } else {
            None
        },
    }
}

/// Whether user timers keep running after logout (`loginctl enable-linger`).
pub fn linger_enabled() -> Option<bool> {
    let out = Command::new("loginctl")
        .args(["show-user", &sys::username(), "-p", "Linger", "--value"])
        .output()
        .ok()?;
    match String::from_utf8_lossy(&out.stdout).trim() {
        "yes" => Some(true),
        "no" => Some(false),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use flux_core::HumanDuration;

    fn env() -> UnitEnv {
        UnitEnv {
            flux_bin: "/usr/bin/flux".into(),
            scope: Scope::User,
            flux_home: None,
        }
    }

    fn profile() -> Profile {
        Profile::new(
            "My Home",
            Target::Local {
                path: "/run/media/me/Disk".into(),
                fs_uuid: None,
            },
            vec!["/home/me".into()],
        )
    }

    #[test]
    fn escaping_matches_systemd() {
        assert_eq!(
            escape_path(Path::new("/run/media/me/Backup")),
            "run-media-me-Backup"
        );
        assert_eq!(
            escape_path(Path::new("/run/media/me/My Disk")),
            "run-media-me-My\\x20Disk"
        );
        assert_eq!(escape_path(Path::new("/mnt/a-b/.x/")), "mnt-a\\x2db-.x");
        assert_eq!(escape_path(Path::new("/")), "-");
    }

    #[test]
    fn manual_needs_no_units() {
        assert!(
            units_for(&ProfileId::new("h").unwrap(), &profile(), &env())
                .unwrap()
                .is_empty()
        );
    }

    #[test]
    fn calendar_units() {
        let mut p = profile();
        p.schedule.trigger = Trigger::Calendar;
        p.schedule.on_calendar = Some("Mon..Fri 18:00".into());
        let u = units_for(&ProfileId::new("home").unwrap(), &p, &env()).unwrap();
        assert_eq!(
            u.iter().map(|x| x.0.as_str()).collect::<Vec<_>>(),
            ["flux-backup-home.service", "flux-backup-home.timer"]
        );
        assert!(u[0].1.starts_with(MARKER));
        assert!(
            u[0].1
                .contains("ExecStart=/usr/bin/flux backup home --scheduled\n")
        );
        assert!(u[0].1.contains("KillSignal=SIGINT"));
        assert!(
            u[1].1
                .contains("OnCalendar=Mon..Fri 18:00\nPersistent=true\n")
        );
    }

    #[test]
    fn interval_units_check_if_due() {
        let mut p = profile();
        p.schedule.trigger = Trigger::Interval;
        p.schedule.every = Some(HumanDuration::from_secs(4 * 3600));
        let u = units_for(
            &ProfileId::new("home").unwrap(),
            &p,
            &UnitEnv {
                flux_home: Some("/x y".into()),
                ..env()
            },
        )
        .unwrap();
        assert!(u[0].1.contains("--scheduled --if-due"));
        assert!(u[0].1.contains("Environment=\"FLUX_HOME=/x y\""));
        assert!(u[1].1.contains("OnUnitActiveSec=900s"));
        assert!(u[1].1.contains("every 4h"));
    }

    #[test]
    fn connect_unit() {
        let mut p = profile();
        p.target = Target::Local {
            path: "/run/media/me/Disk/backups".into(),
            fs_uuid: Some("not-plugged-in".into()),
        };
        p.schedule.on_connect = true;
        let u = units_for(&ProfileId::new("home").unwrap(), &p, &env()).unwrap();
        assert_eq!(u.len(), 1);
        assert_eq!(u[0].0, "flux-backup-home.connect.service");
        assert!(u[0].1.contains("WantedBy=run-media-me-Disk.mount"));
        assert!(u[0].1.contains("Requisite=run-media-me-Disk.mount"));
    }
}
